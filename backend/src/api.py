@app.post("/ask", response_model=ChatResponse, tags=["chat"])
async def ask_query(request: Request, chat_request: ChatRequest):
    """Process user query with retrieval-augmented response.

    Endpoint: POST /ask

    Request:
        {
            "query": "What is physical AI?",
            "top_k": 5,
            "similarity_threshold": 0.7,
            "user_id": "user_123"
        }

    Response:
        {
            "request_id": "uuid",
            "answer": "Physical AI refers to...",
            "sources": [...],
            "context_used": 3,
            "tokens_used": 487,
            "response_time_ms": 1850,
            "timestamp": "2025-12-12T10:30:00Z"
        }

    Args:
        request: FastAPI request object
        chat_request: Chat request with query and parameters

    Returns:
        ChatResponse with answer, sources, and metadata

    Raises:
        HTTPException: For validation errors (400), service errors (503), etc.
    """
    request_id = request.state.request_id
    start_time = time.time()

    try:
        # Validate request
        if not chat_request.query.strip():
            raise HTTPException(
                status_code=400,
                detail=ErrorResponse(
                    request_id=request_id,
                    error="Validation Error",
                    details=[ErrorDetail(field="query", message="Query cannot be empty")],
                    timestamp=datetime.utcnow().isoformat(),
                ).model_dump(),
            )

        logger.info(f"[{request_id}] Query: {chat_request.query[:50]}...")

        # Check if orchestrator initialized
        if rag_orchestrator is None:
            logger.error(f"[{request_id}] RAG orchestrator not initialized")
            raise HTTPException(
                status_code=503,
                detail=ErrorResponse(
                    request_id=request_id,
                    error="Service Unavailable",
                    details=[
                        ErrorDetail(
                            field="service",
                            message="RAG orchestrator not initialized. Check server logs.",
                        )
                    ],
                    timestamp=datetime.utcnow().isoformat(),
                ).model_dump(),
            )

        # Process query
        response = rag_orchestrator.process_query(chat_request)
        response.request_id = request_id  # Ensure consistent request_id
        response.response_time_ms = int((time.time() - start_time) * 1000)

        logger.info(
            f"[{request_id}] Response: {len(response.answer)} chars, "
            f"{response.tokens_used} tokens, {response.response_time_ms}ms, "
            f"{len(response.sources)} sources"
        )

        return response

    except ValidationError as e:
        logger.warning(f"[{request_id}] Validation error: {e}")
        errors = [
            ErrorDetail(field=err["loc"][0], message=err["msg"]) for err in e.errors()
        ]
        raise HTTPException(
            status_code=400,
            detail=ErrorResponse(
                request_id=request_id,
                error="Validation Error",
                details=errors,
                timestamp=datetime.utcnow().isoformat(),
            ).model_dump(),
        )

    except RuntimeError as e:
        logger.error(f"[{request_id}] Processing error: {e}")
        raise HTTPException(
            status_code=503,
            detail=ErrorResponse(
                request_id=request_id,
                error="Service Unavailable",
                details=[ErrorDetail(field="service", message=str(e))],
                timestamp=datetime.utcnow().isoformat(),
            ).model_dump(),
        )

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"[{request_id}] Unexpected error: {e}")
        raise HTTPException(
            status_code=500,
            detail=ErrorResponse(
                request_id=request_id,
                error="Internal Server Error",
                details=[ErrorDetail(field="error", message="An unexpected error occurred")],
                timestamp=datetime.utcnow().isoformat(),
            ).model_dump(),
        )


