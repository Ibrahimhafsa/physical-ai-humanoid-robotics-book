"""
FastAPI application for RAG Agent API.

Exposes `/ask` endpoint for query processing with retrieval-augmented responses.
"""

import logging
import os
import time
from datetime import datetime
from typing import Optional
import uuid

from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import JSONResponse
from fastapi.middleware.cors import CORSMiddleware
from pydantic import ValidationError

from backend.src.models.chat import ChatRequest, ChatResponse, ErrorResponse, ErrorDetail
from backend.src.agent.rag_agent import RAGAgent
from backend.src.agent.orchestrator import RAGOrchestrator
from backend.src.retrieve import QueryEmbedder, QdrantRetriever, ContextExtractor

# Configure logging
logging.basicConfig(
    level=os.getenv("LOG_LEVEL", "INFO"),
    format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
)
logger = logging.getLogger(__name__)

# Initialize FastAPI app
app = FastAPI(
    title="RAG Agent API",
    description="Retrieval-Augmented Generation agent for book chatbot",
    version="0.1.0",
)

# Add CORS middleware
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # Configure appropriately for production
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# Request ID middleware
@app.middleware("http")
async def add_request_id(request: Request, call_next):
    """Add request ID to each request for tracking."""
    request_id = str(uuid.uuid4())
    request.state.request_id = request_id
    response = await call_next(request)
    response.headers["X-Request-ID"] = request_id
    return response


# Initialize components on startup
rag_orchestrator: Optional[RAGOrchestrator] = None


@app.on_event("startup")
async def startup_event():
    """Initialize RAG components on app startup."""
    global rag_orchestrator

    logger.info("Starting RAG Agent API...")

    try:
        # Load configuration from environment
        openai_api_key = os.getenv("OPENAI_API_KEY")
        if not openai_api_key:
            raise ValueError("OPENAI_API_KEY environment variable not set")

        qdrant_url = os.getenv("QDRANT_URL", "http://localhost:6333")
        qdrant_api_key = os.getenv("QDRANT_API_KEY")
        qdrant_collection = os.getenv("QDRANT_COLLECTION", "book_embeddings")
        cohere_api_key = os.getenv("COHERE_API_KEY")

        if not cohere_api_key:
            raise ValueError("COHERE_API_KEY environment variable not set")

        # Initialize components
        logger.info("Initializing retrieval pipeline...")
        embedder = QueryEmbedder(cohere_api_key)
        retriever = QdrantRetriever(qdrant_url, qdrant_api_key, qdrant_collection)
        extractor = ContextExtractor()

        logger.info("Initializing RAG agent...")
        agent = RAGAgent(openai_api_key)

        logger.info("Initializing RAG orchestrator...")
        rag_orchestrator = RAGOrchestrator(
            embedder=embedder,
            retriever=retriever,
            agent=agent,
            extractor=extractor,
            similarity_threshold=float(os.getenv("SIMILARITY_THRESHOLD", "0.5")),
            max_context_tokens=int(os.getenv("MAX_CONTEXT_TOKENS", "6000")),
        )

        logger.info("RAG Agent API startup complete")

    except Exception as e:
        logger.error(f"Startup failed: {e}")
        raise


